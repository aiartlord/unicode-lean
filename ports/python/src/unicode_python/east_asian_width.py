def east_asian_width_value(cp: int) -> str:
    """``East_Asian_Width`` of ``cp``, ``N`` when the file omits it.

    The ranges partition the code space and are sorted by lower
    bound, so the covering range is unique and a binary search finds
    it."""
    lo = 0
    hi = len(EAST_ASIAN_WIDTH_RANGES)
    while lo < hi:
        mid = lo + (hi - lo) // 2
        range_lo, range_hi, value = EAST_ASIAN_WIDTH_RANGES[mid]
        if cp < range_lo:
            hi = mid
        elif cp > range_hi:
            lo = mid + 1
        else:
            return value
    return DEFAULT_EAST_ASIAN_WIDTH
